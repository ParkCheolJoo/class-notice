create table if not exists public.posts (
 id bigint generated by default as identity primary key,
 title text not null check (char_length(title) between 1 and 200),
 content text not null,
 author text not null,
 created_at timestamptz not null default now(),
 likes integer not null default 0 check (likes >= 0),
 category text not null default '학급소식',
 tag text, day text, date text,
 status text not null default 'draft' check (status in ('draft','published','trashed')),
 is_sample boolean not null default false,
 notice_date date not null default (now() at time zone 'Asia/Seoul')::date,
 event_date date,
 pinned boolean not null default false,
 updated_at timestamptz not null default now()
);
create table if not exists public.rankings (
 id bigint generated by default as identity primary key,
 nickname text not null,
 score integer not null default 0 check (score >= 0),
 played_at timestamptz not null default now()
);
alter table public.posts enable row level security;
alter table public.rankings enable row level security;
drop policy if exists "Public notices are readable" on public.posts;
create policy "Public notices are readable" on public.posts for select to anon, authenticated using (status = 'published' and not is_sample);
drop policy if exists "Public rankings are readable" on public.rankings;
-- Rankings are not publicly exposed.
-- Writes are restricted to trusted database administrators. No anonymous writes.
